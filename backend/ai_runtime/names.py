STOP = {"миний", "нэр", "нэрийг", "намайг", "би", "гэдэг", "гэнэ", "байна", "юм", "юу", "уу", "үү", "аа", "өө", "а"}
GENITIVE = re.compile(r"(ын|ийн|гийн|ний|ны)$")


def _norm(s: str) -> str:
    return re.sub(r"[^а-яөүё]", "", s.lower())


VOWELS = set("аэиоуөүеёяюы")


def _lev(a: str, b: str, limit: float) -> float:
    """Levenshtein зай. STT монгол эгшгийг сайн ялгадаггүй ("номин" -> "немо", "билэг" -> "бэлэг")
    тул эгшиг <-> эгшиг солих нь 0.5, бусад нь 1. limit-ээс хэтэрвэл limit+1."""
    if abs(len(a) - len(b)) > limit:
        return limit + 1
    prev = [float(j) for j in range(len(b) + 1)]
    for i, ca in enumerate(a, 1):
        cur = [float(i)]
        for j, cb in enumerate(b, 1):
            sub = 0.0 if ca == cb else (0.5 if ca in VOWELS and cb in VOWELS else 1.0)
            cur.append(min(prev[j] + 1, cur[j - 1] + 1, prev[j - 1] + sub))
        if min(cur) > limit:
            return limit + 1
        prev = cur
    return prev[-1]


def lexicon(extra_path: str | None = None) -> dict[str, str]:
    """norm -> бичих хэлбэр. Бүтэн нэр + хоёр хэсэгтэй нийлмэл нэр + байгууллагын names.txt."""
    out: dict[str, str] = {}
    full = FULL.split()
    if extra_path and os.path.exists(extra_path):
        with open(extra_path, encoding="utf-8") as f:
            full += [ln.strip() for ln in f if ln.strip()]
    parts = PARTS.split()
    for a in parts:
        for b in parts:
            if a != b:
                name = a + b.lower()
                out.setdefault(_norm(name), name)
    for name in full:                     # бүтэн нэр нийлмэлээс давуу
        out[_norm(name)] = name
    return out


def match(text: str, lex: dict[str, str]) -> tuple[str | None, float]:
    """STT-ийн нэр -> (жагсаалтын хамгийн ойр нэр, 0..1 оноо). Олдохгүй бол (None, 0)."""
    words = [w for w in re.findall(r"[а-яөүё-]+", text.lower()) if w not in STOP]
    if not words:
        return None, 0.0
    # "бэлэг сайхан" -> нийлүүлсэн; "Батын Болд" -> овог (ын/ийн)-ыг хасаад сүүлийн үг
    tries = ["".join(words)]
    given = [w for w in words if not GENITIVE.search(w) or _norm(w) in lex]
    if given and given != words:
        tries.append("".join(given))
    # нэрийн өмнө/хойно илүү үг ("ноо мэлмээр"): зэргэлдээ хоёр үг, дараа нь үг бүр
    tries += ["".join(words[i:i + 2]) for i in range(len(words) - 1)] if len(words) > 2 else []
    tries += words[::-1]
    overall = (None, 0.0)
    for t in tries:                      # эхний (бүтэн) хувилбар хангалттай ойр бол түүнийг
        t = _norm(t)
        if not t:
            continue
        if t in lex:
            return lex[t], 1.0
        best, score = None, 0.0
        limit = max(1.5, len(t) / 4)    # 4 үсэг тутамд 1 алдаа (эгшиг 0.5)
        for key, name in lex.items():
            d = _lev(t, key, limit)
            if d <= limit:
                s = 1 - d / max(len(t), len(key))
                if s > score:
                    best, score = name, s
        if score >= 0.8:
            return best, score
        if score > overall[1]:
            overall = (best, score)
    return overall


def best_text(texts: list[str], lex: dict[str, str]) -> str:
    """Хэд хэдэн таниулалтаас нэрсийн жагсаалттай хамгийн сайн таарсныг (тэнцвэл эхнийх).
    "гүгүгү" мэт гацсан, хэт урт үр дүнг алгасна."""
    ok = [t for t in texts if t and len(t) <= 40 and not re.search(r"(\w{1,3})\1{3,}", t)] or texts[:1]
    return max(ok, key=lambda t: match(t, lex)[1])


def fix(text: str, lex: dict[str, str], min_score: float = 0.75) -> str:
    """Нэрийг засна: ойр нэр олдвол түүнийг, эс бөгөөс үгсийг нийлүүлж том үсгээр."""
    name, score = match(text, lex)
    if name and score >= min_score:
        return name
    words = [w for w in re.findall(r"[а-яөүё-]+", text.lower()) if w not in STOP]
    if not words:
        return text.strip()
    if len(words) > 1 and any(GENITIVE.search(w) for w in words[:-1]):   # "Батын Болд" хэвээр
        return " ".join(w.capitalize() for w in words)
    return "".join(words).capitalize()
